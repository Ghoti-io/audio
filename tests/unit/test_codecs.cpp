TEST_F(Codecs, WritingAfterFinishIsRefused) {
  GAUD_Stream * sink = nullptr;
  ASSERT_EQ(gaud_stream_create_memory_writer(nullptr, &sink), GAUD_OK);
  GAUD_Encode_Params params;
  gaud_encode_params_default(&params);
  GAUD_Encoder * encoder = nullptr;
  ASSERT_EQ(gaud_encoder_create("wav", nullptr, sink, &params, &encoder),
      GAUD_OK);
  GAUD_Buffer * b = nullptr;
  ASSERT_EQ(gaud_buffer_create(nullptr, params.format, params.layout,
                GAUD_LAYOUT_INTERLEAVED, 8, &b),
      GAUD_OK);
  gaud_buffer_set_frames(b, 8);
  ASSERT_EQ(gaud_encoder_write(encoder, b), GAUD_OK);
  ASSERT_EQ(gaud_encoder_finish(encoder), GAUD_OK);
  EXPECT_EQ(gaud_encoder_finish(encoder), GAUD_OK) << "finishing is idempotent";
  EXPECT_EQ(gaud_encoder_write(encoder, b), GAUD_ERR_INVALID)
      << "appending past a header that states the length";
  gaud_buffer_destroy(b);
  gaud_encoder_destroy(encoder);
  gaud_stream_destroy(sink);
}

TEST_F(Codecs, EveryFixtureSurvivesARoundTripThroughBothContainers) {
  // Cross-container is the interesting half: reading big-endian and writing
  // little-endian has to be wrong twice to look right.
  struct { const char * file; const char * to; } cases[] = {
      {"wav_s16_stereo_44100.wav", "aiff"},
      {"aiff_s24_stereo_48000.aiff", "wav"},
      {"wav_f32_stereo_48000.wav", "aiff"},
      {"aifc_sowt_stereo_44100.aifc", "wav"},
      {"wav_s16_5dot1_48000.wav", "wav"},
  };
  for (auto & c : cases) {
    Loaded in;
    ASSERT_TRUE(Open(in, c.file)) << c.file;
    std::vector<unsigned char> original = DecodeAll(in.track());

    GAUD_Encode_Params params;
    gaud_encode_params_default(&params);
    params.format = gaud_track_format(in.track());
    params.sample_rate = gaud_track_sample_rate(in.track());
    params.layout = gaud_track_layout(in.track());

    GAUD_Stream * sink = nullptr;
    ASSERT_EQ(gaud_stream_create_memory_writer(nullptr, &sink), GAUD_OK);
    GAUD_Encoder * encoder = nullptr;
    ASSERT_EQ(gaud_encoder_create(c.to, nullptr, sink, &params, &encoder),
        GAUD_OK)
        << c.file << " -> " << c.to;

    GAUD_Buffer * b = nullptr;
    ASSERT_EQ(gaud_buffer_create(nullptr, params.format, params.layout,
                  GAUD_LAYOUT_INTERLEAVED, original.size()
                      / gaud_frame_size(params.format,
                          params.layout.channels),
                  &b),
        GAUD_OK);
    memcpy(gaud_buffer_data(b), original.data(), original.size());
    gaud_buffer_set_frames(b, gaud_buffer_capacity(b));
    ASSERT_EQ(gaud_encoder_write(encoder, b), GAUD_OK);
    ASSERT_EQ(gaud_encoder_finish(encoder), GAUD_OK);
    EXPECT_EQ(gaud_encoder_frames_written(encoder), gaud_buffer_capacity(b));
    gaud_encoder_destroy(encoder);

    const void * written = nullptr;
    size_t length = 0;
    ASSERT_EQ(gaud_stream_writer_bytes(sink, &written, &length), GAUD_OK);
    GAUD_Stream * back = nullptr;
    ASSERT_EQ(gaud_stream_create_memory(written, length, &back), GAUD_OK);
    GAUD_Doc * doc = nullptr;
    ASSERT_EQ(gaud_doc_load(nullptr, back, nullptr, nullptr, &doc), GAUD_OK)
        << c.file << " -> " << c.to;
    std::vector<unsigned char> again = DecodeAll(gaud_doc_track(doc, 0));
    EXPECT_EQ(original, again) << c.file << " -> " << c.to;

    gaud_buffer_destroy(b);
    gaud_doc_destroy(doc);
    gaud_stream_destroy(back);
    gaud_stream_destroy(sink);
  }
}

TEST_F(Codecs, AnOddSampleCountGetsThePadByteAndStillReadsBack) {
  // RIFF and IFF both pad a chunk to an even length, and the pad byte is
  // counted in one size and not the other. A corpus of round numbers never
  // writes one.
  for (const char * codec : {"wav", "aiff"}) {
    GAUD_Encode_Params params;
    gaud_encode_params_default(&params);
    params.format = GAUD_SAMPLE_S8 ; // one byte per sample
    if (strcmp(codec, "wav") == 0) {
      params.format = GAUD_SAMPLE_U8;
    }
    params.layout = gaud_channel_layout_default(1);

    GAUD_Stream * sink = nullptr;
    ASSERT_EQ(gaud_stream_create_memory_writer(nullptr, &sink), GAUD_OK);
    GAUD_Encoder * encoder = nullptr;
    ASSERT_EQ(gaud_encoder_create(codec, nullptr, sink, &params, &encoder),
        GAUD_OK);
    GAUD_Buffer * b = nullptr;
    ASSERT_EQ(gaud_buffer_create(nullptr, params.format, params.layout,
                  GAUD_LAYOUT_INTERLEAVED, 77, &b),
        GAUD_OK);
    gaud_buffer_set_frames(b, 77); // odd: the data chunk needs a pad byte
    ASSERT_EQ(gaud_encoder_write(encoder, b), GAUD_OK);
    ASSERT_EQ(gaud_encoder_finish(encoder), GAUD_OK);
    gaud_encoder_destroy(encoder);

    const void * written = nullptr;
    size_t length = 0;
    gaud_stream_writer_bytes(sink, &written, &length);
    EXPECT_EQ(length % 2, 0u) << codec << ": the file is not padded to even";

    GAUD_Stream * back = nullptr;
    ASSERT_EQ(gaud_stream_create_memory(written, length, &back), GAUD_OK);
    GAUD_Doc * doc = nullptr;
    ASSERT_EQ(gaud_doc_load(nullptr, back, nullptr, nullptr, &doc), GAUD_OK)
        << codec;
    EXPECT_EQ(gaud_track_frames(gaud_doc_track(doc, 0)), 77u)
        << codec << ": the pad byte was counted as a sample";
    gaud_doc_destroy(doc);
    gaud_stream_destroy(back);
    gaud_buffer_destroy(b);
    gaud_stream_destroy(sink);
  }
}

