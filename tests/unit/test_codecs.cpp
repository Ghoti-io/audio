TEST_F(Codecs, BothRegisterAndDeclareAnExactEncoder) {
  const GAUD_Codec * wav = gaud_registry_find(nullptr, "wav");
  const GAUD_Codec * aiff = gaud_registry_find(nullptr, "aiff");
  ASSERT_NE(wav, nullptr);
  ASSERT_NE(aiff, nullptr);
  for (const GAUD_Codec * c : {wav, aiff}) {
    EXPECT_TRUE(c->capabilities & GAUD_CAP_DECODE);
    EXPECT_TRUE(c->capabilities & GAUD_CAP_ENCODE);
    // PCM in a chunk: what comes out is determined by what went in.
    EXPECT_EQ(c->encoder_tier, GAUD_ENCODER_EXACT);
    // The phase 1 fields exist, which is what the size gate reports.
    EXPECT_TRUE(gaud_codec_has(c, offsetof(GAUD_Codec, open)));
    EXPECT_TRUE(gaud_codec_has(c, offsetof(GAUD_Codec, encoder_open)));
  }
}

TEST_F(Codecs, RegisteringTwiceIsHarmless) {
  // codecs.h promises this, so a program that does not know how it was
  // linked can simply call the registration functions.
  size_t before = gaud_registry_count(nullptr);
  gaud_register_builtin_codecs();
  gaud_wav_register();
  EXPECT_EQ(gaud_registry_count(nullptr), before);
}

