TEST_F(Codecs, ReadingInBlocksGivesTheSameSamplesAsReadingInOne) {
  // The short read at the end of a track is the path every decode takes and
  // the one a corpus of round numbers never exercises.
  Loaded f;
  ASSERT_TRUE(Open(f, "wav_s24_stereo_48000.wav"));
  std::vector<unsigned char> small = DecodeAll(f.track(), 97);
  std::vector<unsigned char> large = DecodeAll(f.track(), 100000);
  EXPECT_EQ(small, large);
  EXPECT_EQ(small.size(), 2399u * 6u);
}

TEST_F(Codecs, SeekLandsExactlyWhereItWasAsked) {
  // PCM has no inter-frame state, so this is the case out_landed is
  // trivially true for - which is why callers written against it keep
  // working when a codec arrives for which it is not.
  Loaded f;
  ASSERT_TRUE(Open(f, "wav_s16_stereo_44100.wav"));
  GAUD_Decoder * d = nullptr;
  ASSERT_EQ(gaud_decoder_create(f.track(), &d), GAUD_OK);

  uint64_t landed = 12345;
  ASSERT_EQ(gaud_decoder_seek(d, 1000, &landed), GAUD_OK);
  EXPECT_EQ(landed, 1000u);
  EXPECT_EQ(gaud_decoder_tell(d), 1000u);

  GAUD_Buffer * b = nullptr;
  ASSERT_EQ(gaud_decoder_buffer_create(d, nullptr, 10, &b), GAUD_OK);
  ASSERT_EQ(gaud_decoder_read(d, b), GAUD_OK);
  EXPECT_EQ(gaud_buffer_frames(b), 10u);
  EXPECT_EQ(gaud_decoder_tell(d), 1010u);

  // Seeking to the very end is legal and yields nothing.
  ASSERT_EQ(gaud_decoder_seek(d, gaud_track_frames(f.track()), &landed),
      GAUD_OK);
  ASSERT_EQ(gaud_decoder_read(d, b), GAUD_OK);
  EXPECT_EQ(gaud_buffer_frames(b), 0u);

  // Past the end is not.
  EXPECT_EQ(gaud_decoder_seek(d, gaud_track_frames(f.track()) + 1, &landed),
      GAUD_ERR_INVALID);

  gaud_buffer_destroy(b);
  gaud_decoder_destroy(d);
}

TEST_F(Codecs, TwoDecodersOnOneDocumentDoNotStealEachOthersPosition) {
  // They share a stream. A decoder that assumed it was still where it left
  // the stream would read the other's samples, silently - PCM has no
  // framing to disagree with.
  Loaded f;
  ASSERT_TRUE(Open(f, "wav_s16_stereo_44100.wav"));
  GAUD_Decoder * a = nullptr;
  GAUD_Decoder * b = nullptr;
  ASSERT_EQ(gaud_decoder_create(f.track(), &a), GAUD_OK);
  ASSERT_EQ(gaud_decoder_create(f.track(), &b), GAUD_OK);

  GAUD_Buffer * ba = nullptr;
  GAUD_Buffer * bb = nullptr;
  ASSERT_EQ(gaud_decoder_buffer_create(a, nullptr, 16, &ba), GAUD_OK);
  ASSERT_EQ(gaud_decoder_buffer_create(b, nullptr, 16, &bb), GAUD_OK);

  uint64_t landed = 0;
  ASSERT_EQ(gaud_decoder_seek(b, 500, &landed), GAUD_OK);
  ASSERT_EQ(gaud_decoder_read(a, ba), GAUD_OK); // a is still at 0
  ASSERT_EQ(gaud_decoder_read(b, bb), GAUD_OK); // b is at 500
  EXPECT_EQ(gaud_decoder_tell(a), 16u);
  EXPECT_EQ(gaud_decoder_tell(b), 516u);
  EXPECT_NE(memcmp(gaud_buffer_data_const(ba), gaud_buffer_data_const(bb),
                gaud_buffer_bytes_used(ba)),
      0);

  gaud_buffer_destroy(ba);
  gaud_buffer_destroy(bb);
  gaud_decoder_destroy(a);
  gaud_decoder_destroy(b);
}

TEST_F(Codecs, ReadRefusesABufferThatIsTheWrongShape) {
  // Reading converts nothing, which is the same rule load and save follow,
  // so a mismatched buffer is refused rather than quietly adapted.
  Loaded f;
  ASSERT_TRUE(Open(f, "wav_s16_stereo_44100.wav"));
  GAUD_Decoder * d = nullptr;
  ASSERT_EQ(gaud_decoder_create(f.track(), &d), GAUD_OK);

  GAUD_Buffer * wrong_format = nullptr;
  ASSERT_EQ(gaud_buffer_create(nullptr, GAUD_SAMPLE_S32,
                gaud_channel_layout_default(2), GAUD_LAYOUT_INTERLEAVED, 16,
                &wrong_format),
      GAUD_OK);
  EXPECT_EQ(gaud_decoder_read(d, wrong_format), GAUD_ERR_INVALID);

  GAUD_Buffer * wrong_channels = nullptr;
  ASSERT_EQ(gaud_buffer_create(nullptr, GAUD_SAMPLE_S16,
                gaud_channel_layout_default(1), GAUD_LAYOUT_INTERLEAVED, 16,
                &wrong_channels),
      GAUD_OK);
  EXPECT_EQ(gaud_decoder_read(d, wrong_channels), GAUD_ERR_INVALID);

  GAUD_Buffer * wrong_layout = nullptr;
  ASSERT_EQ(gaud_buffer_create(nullptr, GAUD_SAMPLE_S16,
                gaud_channel_layout_default(2), GAUD_LAYOUT_PLANAR, 16,
                &wrong_layout),
      GAUD_OK);
  EXPECT_EQ(gaud_decoder_read(d, wrong_layout), GAUD_ERR_INVALID);

  // A relabelled mask is NOT a shape change and must be accepted.
  GAUD_Buffer * relabelled = nullptr;
  GAUD_Channel_Layout odd = {GAUD_CH_SIDE_LEFT | GAUD_CH_SIDE_RIGHT, 2};
  ASSERT_EQ(gaud_buffer_create(nullptr, GAUD_SAMPLE_S16, odd,
                GAUD_LAYOUT_INTERLEAVED, 16, &relabelled),
      GAUD_OK);
  EXPECT_EQ(gaud_decoder_read(d, relabelled), GAUD_OK);

  gaud_buffer_destroy(wrong_format);
  gaud_buffer_destroy(wrong_channels);
  gaud_buffer_destroy(wrong_layout);
  gaud_buffer_destroy(relabelled);
  gaud_decoder_destroy(d);
}

