TEST_F(Codecs, LimitsAreRefusalsRatherThanTruncations) {
  // A limit is a stated promise; exceeding one returns GAUD_ERR_LIMIT and
  // never a truncated answer that parses.
  GAUD_Stream * s = nullptr;
  ASSERT_EQ(gaud_stream_create_file(
                Fixture("wav_s16_5dot1_48000.wav").c_str(), &s),
      GAUD_OK);
  GAUD_Limits limits;
  gaud_limits_default(&limits);
  limits.max_channels = 2;
  GAUD_Doc * doc = nullptr;
  EXPECT_EQ(gaud_doc_load(nullptr, s, &limits, nullptr, &doc),
      GAUD_ERR_LIMIT);
  EXPECT_EQ(doc, nullptr);
  gaud_stream_destroy(s);

  ASSERT_EQ(gaud_stream_create_file(
                Fixture("wav_s16_stereo_44100.wav").c_str(), &s),
      GAUD_OK);
  gaud_limits_default(&limits);
  limits.max_frames = 10;
  EXPECT_EQ(gaud_doc_load(nullptr, s, &limits, nullptr, &doc),
      GAUD_ERR_LIMIT);
  gaud_stream_destroy(s);

  ASSERT_EQ(gaud_stream_create_file(
                Fixture("wav_s16_stereo_44100.wav").c_str(), &s),
      GAUD_OK);
  gaud_limits_default(&limits);
  limits.max_sample_rate = 8000;
  EXPECT_EQ(gaud_doc_load(nullptr, s, &limits, nullptr, &doc),
      GAUD_ERR_LIMIT);
  gaud_stream_destroy(s);
}

TEST_F(Codecs, ATruncatedDataChunkIsReportedAndClamped) {
  // A download that stopped states the length it was going to have. A
  // decoder that believed it would return whatever followed in memory.
  GAUD_Stream * file = nullptr;
  ASSERT_EQ(gaud_stream_create_file(
                Fixture("wav_s16_stereo_44100.wav").c_str(), &file),
      GAUD_OK);
  uint64_t size = 0;
  ASSERT_EQ(gaud_stream_size(file, &size), GAUD_OK);
  std::vector<unsigned char> bytes(static_cast<size_t>(size));
  ASSERT_EQ(gaud_stream_read(file, bytes.data(), bytes.size()), bytes.size());
  gaud_stream_destroy(file);

  bytes.resize(bytes.size() / 2); // cut it in half, header intact
  GAUD_Stream * s = nullptr;
  ASSERT_EQ(gaud_stream_create_memory(bytes.data(), bytes.size(), &s),
      GAUD_OK);
  GAUD_Diagnostics diagnostics = {};
  GAUD_Doc * doc = nullptr;
  ASSERT_EQ(gaud_doc_load(nullptr, s, nullptr, &diagnostics, &doc), GAUD_OK);
  EXPECT_LT(gaud_track_frames(gaud_doc_track(doc, 0)), 4409u);
  EXPECT_GT(diagnostics.count, 0u) << "clamping silently would be worse";
  gaud_diagnostics_destroy(&diagnostics);
  gaud_doc_destroy(doc);
  gaud_stream_destroy(s);
}

TEST_F(Codecs, AnEncoderNeedsASeekableSinkAndSaysSoUpFront) {
  // A RIFF header states a length that is not known until the data has been
  // written, so finish() patches it. Discovering that at finish would mean
  // a caller had already written an hour of audio.
  GAUD_Stream * memory = nullptr;
  ASSERT_EQ(gaud_stream_create_memory_writer(nullptr, &memory), GAUD_OK);
  GAUD_Stream * blind = nullptr;
  ASSERT_EQ(gaud_stream_create_unseekable(memory, &blind), GAUD_OK);

  GAUD_Encode_Params params;
  gaud_encode_params_default(&params);
  GAUD_Encoder * encoder = nullptr;
  EXPECT_EQ(gaud_encoder_create("wav", nullptr, blind, &params, &encoder),
      GAUD_ERR_INVALID)
      << "the wrapper is not writable either, which is caught first";

  gaud_stream_destroy(blind);
  gaud_stream_destroy(memory);
}

