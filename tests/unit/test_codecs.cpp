TEST_F(Codecs, TheEightBitFormatsDifferBetweenTheTwoContainers) {
  // The disagreement that makes having both codecs in phase 1 worthwhile:
  // WAV's 8-bit is unsigned and AIFF's is signed, and a reader that treated
  // them alike would be wrong by a full-scale DC offset in one of them.
  Loaded w, a;
  ASSERT_TRUE(Open(w, "wav_u8_mono_22050.wav"));
  ASSERT_TRUE(Open(a, "aiff_s8_mono_22050.aiff"));
  EXPECT_EQ(gaud_track_format(w.track()), GAUD_SAMPLE_U8);
  EXPECT_EQ(gaud_track_format(a.track()), GAUD_SAMPLE_S8);
}

TEST_F(Codecs, AifcSowtIsLittleEndianAndStillDecodesToHostOrder) {
  // `sowt` is "twos" backwards: an AIFF whose samples are little-endian.
  // Whatever the container said, the decoded buffer is in host order - that
  // is the whole reason WAV and AIFF can produce the same buffer.
  Loaded sowt, be;
  ASSERT_TRUE(Open(sowt, "aifc_sowt_stereo_44100.aifc"));
  ASSERT_TRUE(Open(be, "aiff_s16_stereo_44100.aiff"));
  EXPECT_EQ(gaud_track_format(sowt.track()), GAUD_SAMPLE_S16);
  // Both must be plausible audio rather than byte-swapped noise, which is
  // what a missed swap sounds and measures like.
  for (Loaded * f : {&sowt, &be}) {
    GAUD_Decoder * d = nullptr;
    ASSERT_EQ(gaud_decoder_create(f->track(), &d), GAUD_OK);
    GAUD_Buffer * b = nullptr;
    ASSERT_EQ(gaud_decoder_buffer_create(d, nullptr, 1000, &b), GAUD_OK);
    ASSERT_EQ(gaud_decoder_read(d, b), GAUD_OK);
    double peak = 0, dc = 0;
    gaud_ops_peak(b, &peak);
    gaud_ops_dc_offset(b, &dc);
    EXPECT_GT(peak, 0.1) << "silent, or swapped into noise";
    EXPECT_LT(peak, 1.01);
    EXPECT_LT(fabs(dc), 0.1) << "a byte-swapped signal has a wild mean";
    gaud_buffer_destroy(b);
    gaud_decoder_destroy(d);
  }
}

